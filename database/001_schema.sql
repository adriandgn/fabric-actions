BEGIN;

CREATE TABLE IF NOT EXISTS schema_migrations (
  version text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS exhibition_info (
  id integer PRIMARY KEY CHECK (id = 1),
  last_exhibition text NOT NULL DEFAULT '',
  header_label text NOT NULL DEFAULT '',
  next_exhibition text NOT NULL DEFAULT '',
  next_exhibition_date text NOT NULL DEFAULT '',
  next_exhibition_address text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  event_date date,
  location text,
  description text,
  link_url text,
  exhibition_group text NOT NULL DEFAULT 'latest' CHECK (exhibition_group IN ('next', 'latest')),
  position integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS artworks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  year integer,
  description text,
  image_url text,
  position integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS urban_interventions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  date text NOT NULL,
  description text,
  image_url text,
  position integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS event_posts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  subtitle text,
  content text NOT NULL,
  position integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO schema_migrations (version) VALUES ('001_schema') ON CONFLICT DO NOTHING;
COMMIT;
