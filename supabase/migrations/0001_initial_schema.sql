-- 0001_initial_schema.sql

-- Create the events table
CREATE TABLE public.events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  title TEXT NOT NULL,
  event_date DATE NOT NULL,
  location TEXT,
  description TEXT
);

-- Create the artworks table
CREATE TABLE public.artworks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
  title TEXT NOT NULL,
  year INT,
  description TEXT,
  image_url TEXT
);

-- Set up Row Level Security (RLS)
ALTER TABLE public.events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.artworks ENABLE ROW LEVEL SECURITY;

-- Create policies for public read access
CREATE POLICY "Allow public read access to events" ON public.events FOR SELECT USING (true);
CREATE POLICY "Allow public read access to artworks" ON public.artworks FOR SELECT USING (true);

-- Create policies for authenticated admin access (assuming we use the 'authenticated' role)
CREATE POLICY "Allow full access for authenticated users on events" ON public.events FOR ALL USING (auth.role() = 'authenticated') WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "Allow full access for authenticated users on artworks" ON public.artworks FOR ALL USING (auth.role() = 'authenticated') WITH CHECK (auth.role() = 'authenticated');

-- Set up Supabase Storage for artwork images
INSERT INTO storage.buckets (id, name, public) VALUES ('artwork_images', 'artwork_images', true) ON CONFLICT (id) DO NOTHING;

-- Create policies for storage
CREATE POLICY "Allow public read access on artwork images" ON storage.objects FOR SELECT USING (bucket_id = 'artwork_images');
CREATE POLICY "Allow authenticated uploads on artwork images" ON storage.objects FOR INSERT WITH CHECK (bucket_id = 'artwork_images' AND auth.role() = 'authenticated');
CREATE POLICY "Allow authenticated updates on artwork images" ON storage.objects FOR UPDATE WITH CHECK (bucket_id = 'artwork_images' AND auth.role() = 'authenticated');
CREATE POLICY "Allow authenticated deletes on artwork images" ON storage.objects FOR DELETE USING (bucket_id = 'artwork_images' AND auth.role() = 'authenticated');
